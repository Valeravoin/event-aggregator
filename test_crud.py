from database import SessionLocal
# Импортируем фабрику сессий — это то самое «окошко» в базу из database.py

from models import Event
# Нужна, чтобы понимать, что такое Event (иначе не сможем создать объект или искать по нему)

from crud import create_event, get_event_by_id
# Подтягиваем твои рабочие функции: одну для создания, другую для поиска

from datetime import datetime
# Нужен, чтобы задавать конкретные даты и время для тестовых данных

from uuid import uuid4
# Генерирует случайный UUID (уникальный ID). Для теста важно, чтобы ID точно не совпал с чем-то старым


def main():
    # Создаём новую сессию — открываем «окошко» к базе специально для этого теста
    db = SessionLocal()
    try:
        # Генерируем уникальный ID для тестового события. 
        # Так мы уверены, что не перезапишем существующую запись и не получим ошибку дубликата
        test_id = uuid4()
        
        # Вызываем функцию создания события, передавая ей сессию и словарь с данными
        new_event = create_event(
            db=db,
            event_data={
                "id": test_id,
                "name": "Концерт в Севастополе",
                "event_time": datetime(2027, 10, 10, 20, 0),  # Конкретная дата и время
                "status": "published",
                "place_id": "some-place-uuid",
                "place_name": "ДК Рыбаков",
                "city": "Севастополь",
                "address": "ул. Острякова, д. 245",
                "registration_deadline": datetime(2027, 10, 9, 21, 0),
                "number_of_visitors": 3000,
                "last_changed_at": datetime.now(),  # Текущее время прямо в момент запуска теста
            },
        )
        # После вызова create_event внутри уже сработали db.add(), db.commit() и db.refresh()

        print("✅ Событие создано:", new_event.name)
        # Просто выводим подтверждение в консоль, что функция вернула объект

        # Пытаемся найти это же событие по тому ID, который мы только что сгенерировали
        found = get_event_by_id(db, test_id)
        
        if found:
            # Если нашли — выводим имя и статус, чтобы убедиться, что данные сохранились верно
            print("✅ Событие найдено:", found.name, "| статус:", found.status)
        else:
            # Если не нашли — это ошибка логики: создали, но не смогли прочитать
            print("❌ Событие не найдено - ошибка!")

    finally:
        # Блок finally срабатывает всегда: и если всё прошло хорошо, и если случилась ошибка.
        # Это критически важно: закрываем сессию, чтобы не забивать базу открытыми соединениями
        db.close()


if __name__ == "__main__":
    # Эта строчка говорит: «запусти функцию main(), только если ты запустил этот файл напрямую».
    # Если кто-то импортирует этот файл в другой скрипт, main() не запустится автоматически
    main()
